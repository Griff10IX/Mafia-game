const WALL_ROW = '##############';
const mirror = (half) => half + half.split('').reverse().join('');

function build(top, bottom) {
  return [WALL_ROW, ...TOPS[top], ...MIDDLE, ...BOTTOMS[bottom], WALL_ROW].map(mirror);
}

